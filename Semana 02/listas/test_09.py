"""
Listas en Python

sort(): Ordena los elementos de la lista

"""

var_1 = ["SQLServer", "Sass", "RDS", "Mysql", "Postgresql", "MaríaDB", str(27)]
var_2 = [50.9, 100, 0.5, 2, 800, 1080]

var_1.sort()
var_2.sort()

print("1era lista ordenada: {}".format(var_1))
print("2da lista ordenada: {}".format(var_2))

